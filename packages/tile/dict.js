/** The 25 bits of marker `id` as a number (bit 24 = top-left cell). */
export function markerCode(id) {
  if (!Number.isInteger(id) || id < 0 || id >= DICT_SIZE) throw new RangeError(`marker id ${id} is not in ${DICT_NAME}`);
  return parseInt(HEX.slice(id * 7, id * 7 + 7), 16);
}

/** The bits of marker `id` as rows of 0/1, top row first: what to paint inside the black border. */
export function markerBits(id) {
  const c = markerCode(id), rows = [];
  for (let y = 0; y < DICT_BITS; y++) {
    const r = [];
    for (let x = 0; x < DICT_BITS; x++) r.push((c >> (DICT_BITS * DICT_BITS - 1 - (y * DICT_BITS + x))) & 1);
    rows.push(r);
  }
  return rows;
}
